#!/usr/bin/env node
// Turns the curated list into the data block inside games/opposites/index.html.
//
//   node tools/build_opposites_data.mjs           validate, then rewrite the block between BEGIN_WORD_PAIRS / END_WORD_PAIRS
//   node tools/build_opposites_data.mjs --check   validate, and fail if the block in the game is out of date (used by build.sh)
//
// Sources:  tools/opposites-words.txt        the list (format in tools/opposites-lib.mjs)
//           tools/opposites-misspellings.txt common misspellings, accepted as correct when typed
//           tools/opposites-forms.txt        word forms (smaller, pulled, went), accepted as correct when typed
// Each entry becomes one compact line:
//   {"w":"happy","a":["sad",...],"t":["unhapy",...],"d":["lamp",...],"l":1}
//   w  question word            a  answers, offered as tap choices and accepted when typed
//   t  accepted only when typed (informal words marked ~, plus the forms and common misspellings of every answer)
//   d  distractors (never acceptable)      l  level (1 = about age 5, 2 = ages 6 to 7)
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { parseWords } from './opposites-lib.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.dirname(HERE);
const WORDS = path.join(HERE, 'opposites-words.txt');
const MISS = path.join(HERE, 'opposites-misspellings.txt');
const FORMS = path.join(HERE, 'opposites-forms.txt');
const GAME = path.join(ROOT, 'games', 'opposites', 'index.html');
const BEGIN = '// BEGIN_WORD_PAIRS';
const END = '// END_WORD_PAIRS';
const check = process.argv.includes('--check');

// 1. validate first: never embed data that fails its own rules
try {
  execFileSync(process.execPath, [path.join(HERE, 'validate-opposites.mjs')], { stdio: 'pipe' });
} catch (e) {
  process.stderr.write(String(e.stdout || '') + String(e.stderr || ''));
  console.error('Opposites list failed validation; data not touched.');
  process.exit(1);
}

// 2. build entries
const { entries } = parseWords(fs.readFileSync(WORDS, 'utf8'));
const readMap = (file) => { // "answer: word word" lines -> Map(answer -> [words])
  const out = new Map();
  for (const raw of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = raw.replace(/#.*$/, '').trim().match(/^([a-z]+):\s*([a-z ]+)$/);
    if (m) out.set(m[1], m[2].trim().split(/\s+/));
  }
  return out;
};
const slips = readMap(MISS);   // answer -> common misspellings
const forms = readMap(FORMS);  // answer -> word forms
const rows = entries.map((e) => {
  const typed = [];
  for (const t of e.typedOnly) if (!typed.includes(t)) typed.push(t);
  for (const a of e.answers) for (const s of [...(forms.get(a) || []), ...(slips.get(a) || [])]) if (!typed.includes(s)) typed.push(s);
  const choosable = e.answers.filter((a) => !e.typedOnly.includes(a));
  return { w: e.word, a: choosable, t: typed, d: e.distractors, l: e.level };
});
const block = `${BEGIN}\n// Generated by tools/build_opposites_data.mjs from tools/opposites-words.txt, opposites-misspellings.txt and opposites-forms.txt. Do not edit here.\nconst wordPairs = [\n${rows.map((r) => JSON.stringify(r)).join(',\n')}\n];\n${END}`;

// 3. patch (keeping the file's own line endings)
const html = fs.readFileSync(GAME, 'utf8');
const eol = html.includes('\r\n') ? '\r\n' : '\n';
const re = new RegExp(`${BEGIN}[\\s\\S]*?${END}`);
if (!re.test(html)) { console.error(`Markers ${BEGIN} / ${END} not found in ${GAME}`); process.exit(1); }
const next = html.replace(re, () => block.replace(/\n/g, eol));
if (check) {
  if (next !== html) { console.error('games/opposites/index.html is out of date. Run: node tools/build_opposites_data.mjs'); process.exit(1); }
  console.log(`Opposites data is current (${rows.length} entries).`);
} else {
  fs.writeFileSync(GAME, next);
  console.log(`Wrote ${rows.length} entries to games/opposites/index.html (data block ${block.length} bytes).`);
}
